/**
 * Check if a position is walkable, using the character's foot point.
 */
function isTileWalkable(worldX: number, worldY: number): boolean {
    const col = Math.floor(worldX / TILE_SIZE);
    const row = Math.floor(worldY / TILE_SIZE);
    if (col < 0 || col >= GRID_WIDTH || row < 0 || row >= GRID_HEIGHT) return false;
    return COLLISION_GRID[row][col] === 0;
}

/**
 * Check if a world-space position is clear for the character's bounding box.
 * Checks 4 corners of the character's hitbox around their center point.
 */
export function isWalkable(worldX: number, worldY: number): boolean {
    // Check all 4 corners of the character hitbox
    return (
        isTileWalkable(worldX - CHAR_HALF_W, worldY - CHAR_HALF_H) &&
        isTileWalkable(worldX + CHAR_HALF_W, worldY - CHAR_HALF_H) &&
        isTileWalkable(worldX - CHAR_HALF_W, worldY + CHAR_HALF_H) &&
        isTileWalkable(worldX + CHAR_HALF_W, worldY + CHAR_HALF_H)
    );
}

/**
 * Try to move from (x,y) by (dx,dy), handling wall sliding.
 * If full movement blocked, tries sliding along each axis independently.
 * Also tries smaller steps for better collision hugging.
 * Returns the final walkable position.
 */
export function resolveMovement(
    x: number,
    y: number,
    dx: number,
    dy: number
): { x: number; y: number } {
    const newX = x + dx;
    const newY = y + dy;

    // Try full movement first
    if (isWalkable(newX, newY)) {
        return { x: newX, y: newY };
    }

    // Try sliding along X only
    if (dx !== 0 && isWalkable(newX, y)) {
        return { x: newX, y };
    }

    // Try sliding along Y only
    if (dy !== 0 && isWalkable(x, newY)) {
        return { x, y: newY };
    }

    // Try half-step X sliding (gets closer to walls)
    const halfX = x + dx * 0.5;
    if (dx !== 0 && isWalkable(halfX, y)) {
        return { x: halfX, y };
    }

    // Try half-step Y sliding
    const halfY = y + dy * 0.5;
    if (dy !== 0 && isWalkable(x, halfY)) {
        return { x, y: halfY };
    }

    // Fully blocked: stay in place
    return { x, y };
}
